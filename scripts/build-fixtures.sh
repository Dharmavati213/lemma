#!/usr/bin/env bash
# Generates the fixtures that are too large or too slow to commit, under target/fixtures/:
#   pdf50.tex/.pdf/.synctex.gz  50 pages of lipsum text and display math, one section per page,
#                               with hyperref cross-references (PdfView scrolling, cache, links)
#   doc1k.tex                   the first 999 lines of tests/fixtures/large.tex plus \end{document}
#                               (the 1k-line idle memory scenario in scripts/budgets.toml)
# Idempotent: unchanged sources are not rewritten, and latexmk skips up-to-date builds.
# The TeX build runs in target/fixtures, never in tests/fixtures.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/target/fixtures"
PAGES=50

die() { echo "build-fixtures.sh: $*" >&2; exit 1; }

for tool in latexmk pdflatex pdfinfo kpsewhich; do
  command -v "$tool" >/dev/null || die "$tool is required"
done
for sty in lipsum.sty amsmath.sty hyperref.sty geometry.sty; do
  kpsewhich "$sty" >/dev/null || die "the TeX package $sty is not installed"
done
mkdir -p "$OUT"

# Writes stdin to $1 only if the content changed, so mtimes stay stable.
write_if_changed() {
  local dest="$1" tmp
  tmp="$(mktemp "$dest.XXXXXX")"
  cat >"$tmp"
  if cmp -s "$tmp" "$dest"; then
    rm -f "$tmp"
  else
    chmod 0644 "$tmp"
    mv "$tmp" "$dest"
  fi
}

pdf50_tex() {
  cat <<'TEX'
% Generated by scripts/build-fixtures.sh; do not edit.
% One section per page: two lipsum paragraphs, an aligned display and a matrix, then \clearpage.
\documentclass[11pt]{article}
\usepackage[a4paper,margin=2.5cm]{geometry}
\usepackage{amsmath,amssymb}
\usepackage{lipsum}
\usepackage{hyperref}
\begin{document}
TEX
  local k prev
  for ((k = 1; k <= PAGES; k++)); do
    prev=$(( k > 1 ? k - 1 : PAGES ))
    cat <<TEX

\section{Section ${k}}\label{sec:${k}}
\lipsum[$(( (2 * k - 2) % 50 + 1 ))]
\begin{align}
  f_{${k}}(x) &= \sum_{n=0}^{\infty} \frac{x^{n}}{(n+${k})!}, \label{eq:${k}}\\\\
  \int_{0}^{1} f_{${k}}(x)\,\mathrm{d}x &= \lim_{N\to\infty} \sum_{n=0}^{N} \frac{1}{(n+1)\,(n+${k})!}
    \le e - \sum_{j<${k}} \frac{1}{j!}.
\end{align}
Compare Section~\ref{sec:${prev}} and equation~\eqref{eq:${prev}}.
\[
  A_{${k}} = \begin{pmatrix} \alpha_{${k}} & \beta \\\\ \gamma & \delta_{${k}} \end{pmatrix},
  \qquad \det A_{${k}} = \alpha_{${k}}\delta_{${k}} - \beta\gamma \in \mathbb{R}.
\]
\lipsum[$(( (2 * k - 1) % 50 + 1 ))]
\clearpage
TEX
  done
  printf '\\end{document}\n'
}

pdf50_tex | write_if_changed "$OUT/pdf50.tex"
{ head -n 999 "$ROOT/tests/fixtures/large.tex"; printf '\\end{document}\n'; } | write_if_changed "$OUT/doc1k.tex"

echo "build-fixtures.sh: building target/fixtures/pdf50.pdf"
if ! (cd "$OUT" && latexmk -pdf -synctex=1 -interaction=nonstopmode -halt-on-error -file-line-error \
        pdf50.tex </dev/null >pdf50.latexmk.out 2>&1); then
  tail -n 40 "$OUT/pdf50.latexmk.out" >&2
  die "latexmk failed; see target/fixtures/pdf50.latexmk.out and pdf50.log"
fi

pages="$(pdfinfo "$OUT/pdf50.pdf" | awk '$1 == "Pages:" { print $2 }')"
[ "$pages" = "$PAGES" ] || die "pdf50.pdf has ${pages:-no} pages, expected $PAGES"
[ -s "$OUT/pdf50.synctex.gz" ] || die "pdf50.synctex.gz was not written"
echo "build-fixtures.sh: target/fixtures/pdf50.pdf ($pages pages), target/fixtures/doc1k.tex ($(wc -l <"$OUT/doc1k.tex") lines)"
